-- =========================================================
-- medidas — peso corporal e circunferências
--
-- Rode isto uma vez no SQL Editor do Supabase.
-- É seguro rodar de novo: tudo é "if not exists" ou recriado.
--
-- Uma linha por DIA, não por pesagem: `unique (user_id, data)`.
-- Pesar duas vezes no mesmo dia é ruído de balança, não dado;
-- a segunda medição substitui a primeira em vez de criar outra
-- linha e sujar o gráfico.
--
-- Todas as medidas são opcionais menos a data: num dia você pesa,
-- no outro tira a fita métrica. Coluna vazia é "não medi", que é
-- diferente de zero — por isso nenhuma tem default 0.
-- =========================================================

create table if not exists public.medidas (
  id           bigint generated by default as identity primary key,
  user_id      uuid        not null references auth.users(id) on delete cascade,
  data         date        not null,

  peso         numeric(5,2),   -- kg
  gordura      numeric(4,1),   -- %, se a balança disser

  -- circunferências em cm
  cintura      numeric(5,1),
  quadril      numeric(5,1),
  peito        numeric(5,1),
  braco        numeric(5,1),
  coxa         numeric(5,1),
  panturrilha  numeric(5,1),

  nota         text,
  criado_em    timestamptz not null default now(),

  unique (user_id, data)
);

create index if not exists medidas_user_data_idx
  on public.medidas (user_id, data desc);

-- =========================================================
-- SEGURANÇA (RLS)
--
-- Sem isto, qualquer pessoa com a publishable key lê a tabela
-- inteira. Com isto, o Postgres compara auth.uid() com user_id
-- em toda consulta e devolve só o que é seu.
-- =========================================================

alter table public.medidas enable row level security;

drop policy if exists "medidas: dono lê"       on public.medidas;
drop policy if exists "medidas: dono insere"   on public.medidas;
drop policy if exists "medidas: dono atualiza" on public.medidas;
drop policy if exists "medidas: dono apaga"    on public.medidas;

create policy "medidas: dono lê"
  on public.medidas for select
  using (auth.uid() = user_id);

create policy "medidas: dono insere"
  on public.medidas for insert
  with check (auth.uid() = user_id);

create policy "medidas: dono atualiza"
  on public.medidas for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "medidas: dono apaga"
  on public.medidas for delete
  using (auth.uid() = user_id);

-- confere que ligou mesmo
select tablename, rowsecurity
from pg_tables
where schemaname = 'public' and tablename = 'medidas';
